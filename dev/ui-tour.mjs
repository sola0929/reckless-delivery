// Every screen over the game: the opening card, driving, paused, the result; and the main menu's pages. node dev/ui-tour.mjs [w] [h]
import { chromium } from 'playwright-core';
const [w, h] = [Number(process.argv[2] ?? 1280), Number(process.argv[3] ?? 720)];
const b = await chromium.launch({ channel: 'msedge', args: ['--ignore-gpu-blocklist', '--enable-gpu', '--use-angle=d3d11'] });
const p = await b.newPage({ viewport: { width: w, height: h } });
const errors = []; p.on('pageerror', (e) => errors.push(String(e)));
const shot = (name) => p.screenshot({ path: `dev/out/tour-${name}.png` });
await p.goto('http://localhost:5183/');
await p.waitForTimeout(1200);
await shot('home');
await p.click('[data-page="menu-settings"]');
await p.waitForTimeout(600);
await shot('settings');
await p.goto('http://localhost:5183/?level=uptown');
await p.waitForTimeout(700);
await shot('loading');
await p.waitForFunction(() => window.game?.sim && document.getElementById('loading').hidden, null, { timeout: 90000 });
await p.waitForTimeout(800);
await shot('banner');
await p.keyboard.press('Enter');
await p.keyboard.down('KeyW');
await p.waitForTimeout(3000);
await p.keyboard.up('KeyW');
await shot('driving');
await p.waitForTimeout(13000);
await shot('tucked');
await p.keyboard.press('Escape');
await p.waitForTimeout(500);
await shot('pause');
await p.keyboard.press('Escape');
await p.evaluate(() => window.game.sim.teleport(-370, 992, 0));
await p.waitForTimeout(6000);
await shot('result');
  console.log('focused:', await p.evaluate(() => document.activeElement?.id + ' ' + document.activeElement?.textContent));
console.log(errors.length ? errors.join('\n') : 'no page errors');
await b.close();
